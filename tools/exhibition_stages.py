def ready(dep):
    s=dep.get('status',{});n=dep['spec'].get('replicas',1)
    return (n==1 and not dep['metadata'].get('deletionTimestamp') and s.get('observedGeneration')==dep['metadata']['generation']
            and s.get('replicas')==n and s.get('readyReplicas')==n and s.get('updatedReplicas')==n
            and s.get('availableReplicas')==n and not s.get('unavailableReplicas') and not s.get('terminatingReplicas'))


def stopped(policy,uid):
    m=policy['metadata'];s=policy.get('status',{})
    require(m['uid']==uid and not m.get('deletionTimestamp') and not policy['spec']['enabled'] and not s.get('activeIncident') and
            any(c.get('type')=='Quiesced' and c.get('status')=='True' and c.get('reason')=='FenceClosed' and c.get('observedGeneration')==m['generation'] for c in s.get('conditions',[])), 'CURRENT_FENCE_REQUIRED')


def template(value):
    value=copy.deepcopy(value)
    # The only field generated by the ReplicaSet controller, explicitly scoped
    # to template comparison. Raw /spec and full Incident hashes are untouched.
    value['metadata'].get('labels',{}).pop('pod-template-hash',None)
    return value


def replicasets(dep,rs_list):
    require(not rs_list.get('metadata',{}).get('continue'),'RS_INVENTORY_INCOMPLETE')
    items=rs_list['items']
    require(all(not r['metadata'].get('deletionTimestamp') for r in items),'RS_TERMINATION_UNCONFIRMED')
    owned=[r for r in items if any(o.get('kind')=='Deployment' and o.get('controller') is True and o.get('uid')==dep['metadata']['uid'] for o in r['metadata'].get('ownerReferences',[]))]
    require(len(owned)==len(items),'FOREIGN_RS_QUOTA_CONFLICT')
    return owned


def template_uid(rs,target):
    matches=[r['metadata']['uid'] for r in rs if template(r['spec']['template'])==template(target)]
    require(len(matches)<=1,'TEMPLATE_IDENTITY_AMBIGUOUS')
    return matches[0] if matches else None


def capacity(dep,rs_list,quota,desired_templates,*,runtime_new=0):
    """Explicit phase peak: exact retained templates may be reused, no GC credit.

    Never subtract planned deletions. Between phases wait/observe ordinary
    rollout/GC and re-evaluate rather than assuming a future count.
    """
    rs=replicasets(dep,rs_list);used=len(rs);additional=runtime_new;reused=[];new=[]
    for desired in desired_templates:
        uid=template_uid(rs,desired)
        if uid:reused.append(uid)
        elif digest(template(desired)) not in new:new.append(digest(template(desired)));additional+=1
    limits=[]
    for q in quota['items']:
        hard=q['spec']['hard'];status=q.get('status',{})
        require(hard==status.get('hard') and not q['spec'].get('scopes') and not q['spec'].get('scopeSelector'),'QUOTA_STATUS_UNCONFIRMED')
        if 'count/replicasets.apps' in hard:
            used=max(used,int(status['used']['count/replicasets.apps']));limits.append(int(hard['count/replicasets.apps']))
    require(bool(limits),'RS_QUOTA_REQUIRED')
    require(used+additional<=min(limits),'STAGE_RS_HEADROOM_INSUFFICIENT')
    # Preparation: one surge Pod. Experiment plus fault/action/restore can
    # transiently retain three old Pods; reserve all four, never future GC.
    pod_extra = 3 if runtime_new else 1
    require(dep['spec'].get('replicas')==1 and dep['spec'].get('revisionHistoryLimit')==2 and
            dep['spec'].get('strategy')=={'type':'RollingUpdate','rollingUpdate':{'maxUnavailable':0,'maxSurge':1}},'ROLLOUT_BOUNDS_CHANGED')
    from tools.exhibition_readiness import quantity
    c=dep['spec']['template']['spec']['containers'];require(len(c)==1,'APP_RESOURCE_LAYOUT_CHANGED')
    for q in quota['items']:
        for resource,limit in q['spec']['hard'].items():
            if resource in ('pods','count/pods'):extra=pod_extra
            elif resource.startswith(('requests.','limits.')):
                group,name=resource.split('.',1);extra=pod_extra*quantity(c[0]['resources'][group][name])
            else:continue
            require(quantity(q['status']['used'][resource])+extra<=quantity(limit),'STAGE_RESOURCE_HEADROOM_INSUFFICIENT')
    return {'resource':'count/replicasets.apps','current':used,'additionalUpperBound':additional,'peakUpperBound':used+additional,'hard':min(limits),'reusedUIDs':reused,'futureGCCountedAsAvailable':False}


def baseline_transform(plan,key,dep):
    t=plan['fixedTargets'][key];verify(dep,t['observedDeploymentSpecHash'],fields='/spec')
    out=copy.deepcopy(dep);ops=[]
    if key=='b':
        env=out['spec']['template']['spec']['containers'][0]['env']
        require(env[5]=={'name':'DEMO_B_REPLAY','value':'empty-order-after-30s'},'REPLAY_SOURCE_CHANGED')
        del env[5]['value'];ops=[{'op':'remove','path':'/spec/template/spec/containers/0/env/5/value'}]
    return out,ops


def pod_inventory(plan,key,objects,*,require_ready=False):
    t=plan['fixedTargets'][key];pods=objects[key+'-pods'];require(not pods.get('metadata',{}).get('continue'),'POD_INVENTORY_INCOMPLETE')
    history={p['object']['uid'] for r in plan['readinessContract']['historicalJobs'] for p in r['pods']}
    rs=replicasets(objects[key+'-deployment'],objects[key+'-replicasets']);owners={r['metadata']['uid'] for r in rs};app=[]
    for p in pods['items']:
        if p['metadata']['uid'] in history:continue
        require(not p['metadata'].get('deletionTimestamp') and any(o.get('kind')=='ReplicaSet' and o.get('controller') is True and o.get('uid') in owners for o in p['metadata'].get('ownerReferences',[])),'FOREIGN_OR_TERMINATING_POD')
        app.append(p)
    require(len(app)==1 and app[0]['status']['phase']=='Running','BASELINE_POD_INVENTORY_UNCONFIRMED')
    if require_ready:require(any(c.get('type')=='Ready' and c.get('status')=='True' for c in app[0]['status'].get('conditions',[])),'BASELINE_POD_NOT_READY')
    return {'appPods':len(app),'preservedHistoricalPodUIDs':len(history)}


def preparation_gate(plan,objects):
    """Allows the exact B restore from NotReady; never allows Enforce here."""
    result={}
    for key,t in plan['fixedTargets'].items():
        dep=objects[key+'-deployment'];pol=objects[key+'-policy'];inc=objects[key+'-incident']
        verify(pol,t['policySpecHash'],fields='/spec');stopped(pol,t['policyUID'])
        require(pol['metadata']['generation']==t['observedPolicyGeneration'] and pol.get('status',{}).get('incidentSequence',0)==t['observedIncidentSequence'],'POLICY_HISTORY_CHANGED')
        if key=='a' and 'continuation' in plan:
            from tools.exhibition_deletion import archived_incident
            inc=archived_incident(plan,key,inc)
        verify(inc,plan['objectHashContract']['objects'][key+'-incident'],fields='/')
        status=inc['status']['runtime'];require(status['phase'] in ('RECOVERED','FAILED') and status.get('completedAt') and not status.get('oldPodsOutstanding') and not inc['metadata'].get('finalizers'),'MIGRATION_TERMINATION_REQUIRED')
        pod_inventory(plan,key,objects)
        base,ops=baseline_transform(plan,key,dep)
        result[key]={'gate':'PREPARATION_INPUTS_MATCH','observedReady':ready(dep),'restoreRequired':bool(ops),'enforceAuthorized':False,
                     'baselineSpecHash':describe(base,'/spec'),'restorePatch':ops,
                     'capacity':capacity(dep,objects[key+'-replicasets'],objects[key+'-quotas'],[base['spec']['template']])}
    return result


def experiment_gate(plan,key,dep,policy,rs,quota,instance,expected_instance):
    t=plan['fixedTargets'][key];verify(dep,t['baselineSpecHash'],fields='/spec');stopped(policy,t['policyUID'])
    require(ready(dep),'BASELINE_READY_REQUIRED_BEFORE_ENFORCE')
    require(instance and instance==expected_instance,'CURRENT_DEPLOYED_INSTANCE_REQUIRED')
    desired=[]
    if key=='b':
        fault=copy.deepcopy(dep['spec']['template']);fault['spec']['containers'][0]['env'][5]['value']='empty-order-after-30s';desired.append(fault)
    # Exactly one Runtime action creates one attempt template. Restore must reuse
    # the exact baseline RS retained by historyLimit=2, not synthesize another.
    owned=replicasets(dep,rs);require(template_uid(owned,dep['spec']['template']),'BASELINE_RS_REQUIRED')
    return capacity(dep,rs,quota,desired,runtime_new=1)


def next_gate(ref, *, previous_binding, plan, key, dep, policy, rs, quota, instance, expected_instance):
    completion=verify_completion(ref['path'],ref['sha256'])
    require(completion.get('binding')==previous_binding and completion.get('nextRunAllowed') is True,'PREVIOUS_COMPLETION_REQUIRED')
    for field in ('stopConfirmed','baselineRestored','modelStopped','evidenceArchived','objectsCleaned'):
        require(completion.get(field) is True,'PREVIOUS_LIFECYCLE_INCOMPLETE')
    return experiment_gate(plan,key,dep,policy,rs,quota,instance,expected_instance)
